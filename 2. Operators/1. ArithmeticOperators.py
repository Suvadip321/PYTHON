"""
LESSON: Arithmetic Operators
─────────────────────────────
+   Addition
-   Subtraction
*   Multiplication
/   Division (returns float)
//  Floor Division (truncates decimal)
%   Modulus (remainder)
**  Exponent (power)
"""

a = 15
b = 4

print("a + b  =", a + b)    # 19
print("a - b  =", a - b)    # 11
print("a * b  =", a * b)    # 60
print("a / b  =", a / b)    # 3.75
print("a // b =", a // b)   # 3
print("a % b  =", a % b)    # 3
print("a ** b =", a ** b)   # 50625
